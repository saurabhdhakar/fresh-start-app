export const DICTIONARIES: Record<string, Dict> = {
  en,
  en_in: en,
  hinglish,
  hi,
  ta,
  te,
  kn,
  ml,
  ar,
  fr,
};

/** Language-agnostic lookup — usable outside React components. */
export function translate(language: string, key: TranslationKey): string {
  return DICTIONARIES[language]?.[key] ?? en[key] ?? key;
}

/** English-only lookup (used by the pre-language country screen). */
export function tEn(key: TranslationKey): string {
  return en[key] ?? key;
}

type I18nValue = {
  language: string;
  setLanguage: (l: string) => void;
  t: (key: TranslationKey) => string;
  dir: "ltr" | "rtl";
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({
  language,
  setLanguage,
  children,
}: {
  language: string;
  setLanguage: (l: string) => void;
  children: ReactNode;
}) {
  const dir: "ltr" | "rtl" = RTL_LANGUAGES.has(language) ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = language === "hinglish" ? "en-IN" : language.replace("_", "-");
    document.documentElement.dir = dir;
    return () => {
      document.documentElement.dir = "ltr";
    };
  }, [language, dir]);

  const value = useMemo<I18nValue>(
    () => ({
      language,
      setLanguage,
      dir,
      t: (key) => DICTIONARIES[language]?.[key] ?? en[key] ?? key,
    }),
    [language, setLanguage, dir],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    return {
      language: "en",
      setLanguage: () => {},
      dir: "ltr",
      t: (key) => en[key] ?? key,
    };
  }
  return ctx;
}

export function useT() {
  return useI18n().t;
}
